import type { ActionDef, EffectDef, EnemyDef } from '@/core/types';

/**
 * Foes of the contract battlefields (src/content/themes.ts). Each battlefield has four new characters (two regulars, an
 * elite and its guardian) and three recoloured variants of Mortal foes (`look`, same sprite). Stats follow the Mortal
 * realm they replace: Realm I regulars cost 1-2 (elite 6, guardian 20), Realm II regulars 1.3-3.2 (elite 8, guardian 30);
 * contracts add their own modifiers and the Tribulation Level scales them all.
 */

// ───────────────────────── helpers ─────────────────────────

const onHit = (id: string, name: string, desc: string, actions: ActionDef[], chance?: number): EffectDef => ({
  id,
  name,
  desc,
  trigger: { on: 'autoAttack' },
  ...(chance ? { conditions: [{ if: 'chance' as const, pct: chance }] } : {}),
  actions,
});
const every = (id: string, name: string, desc: string, sec: number, after: number, actions: ActionDef[]): EffectDef => ({ id, name, desc, trigger: { on: 'interval', every: sec, after }, actions });
const below = (id: string, name: string, desc: string, pct: number, actions: ActionDef[]): EffectDef => ({ id, name, desc, trigger: { on: 'hpBelow', pct }, actions });
const onDeath = (id: string, name: string, desc: string, actions: ActionDef[]): EffectDef => ({ id, name, desc, trigger: { on: 'death' }, actions });
const ENRAGE: ActionDef = { do: 'custom', id: 'bossEnrage' };
const adjacent = { kind: 'enemiesAdjacent' as const, radius: 1 };
const nearest = (count: number) => ({ kind: 'nearestEnemies' as const, count });

